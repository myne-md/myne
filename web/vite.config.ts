function platformSeamSubstitution(): Plugin {
  return {
    name: "myne:platform-seam-substitution",
    // `pre` so the redirect happens before any other resolver claims the id.
    enforce: "pre",
    async resolveId(source, importer, options) {
      // Never redirect an import made BY web-side code. Substitution exists so
      // that the SHARED tree's own imports land on web implementations; a web
      // module asking for a shared module wants the shared one — the web seam
      // imports `src/platform/unsupported` for the shared error type, and a
      // substitute screen re-exports the constants it does not override from
      // the very module it replaces. Without this the second case resolves to
      // itself and rolldown reports a circular re-export, which is the honest
      // failure but not the useful one.
      if (importer && importer.startsWith(path.join(repoRoot, "web", "src") + path.sep)) {
        return null;
      }

      const resolved = await this.resolve(source, importer, {
        ...options,
        skipSelf: true,
      });
      if (!resolved) return null;

      // Shared modules the web build replaces wholesale, checked before the
      // seam rule because they live outside `src/platform/`.
      const withoutExt = resolved.id.replace(/\.[tj]sx?$/, "");
      const substitute = SUBSTITUTED_MODULES[withoutExt];
      if (substitute !== undefined) {
        const replacement = await this.resolve(substitute, importer, {
          ...options,
          skipSelf: true,
        });
        if (!replacement) {
          this.error(
            `web bundle: no substitute for '${path.relative(repoRoot, resolved.id)}'. ` +
              `A module listed in SUBSTITUTED_MODULES needs a counterpart under web/src/.`,
          );
        }
        return replacement;
      }

      if (!resolved.id.startsWith(desktopSeam + path.sep)) return null;

      const rel = path.relative(desktopSeam, resolved.id);
      // `unsupported.ts` is shared vocabulary, not a platform implementation —
      // both seams throw the same error type, so it is deliberately NOT
      // substituted.
      if (rel.replace(/\.[tj]sx?$/, "") === "unsupported") return null;

      const target = path.join(webSeam, rel.replace(/\.[tj]sx?$/, ""));
      const web = await this.resolve(target, importer, { ...options, skipSelf: true });
      if (!web) {
        this.error(
          `platform seam: no web implementation for '${rel}'. ` +
            `Every module in src/platform/ needs a counterpart in web/src/platform/.`,
        );
      }
      return web;
    },
  };
}

/**
 * Emit CSS `data:` image URIs as same-origin files (phase3-web-client task 99).
 *
 * # Why the CSP is not widened instead
 *
 * `img-src 'self' blob:` is the policy task 97 narrowed to, and task 44's
 * criterion is that it admit object URLs **without** admitting `data:`. A `data:`
 * source admits any bytes any script can construct — that is exactly what the
 * directive refuses, and re-adding it to keep a decoration working would be
 * trading the property for a swatch.
 *
 * # What is actually broken without this
 *
 * The vendored drawing-canvas stylesheet paints its transparent-background
 * checkerboard from an inline 16×16 PNG. Under the production CSP the browser
 * refuses it: the swatch renders flat and a violation is logged on every drawing
 * open. **Cosmetic, and therefore quiet** — which is the whole reason it needs a
 * build rule rather than a bug report. It would also trip task 60's
 * "zero CSP violations" assertion, where it would read as a mystery rather than
 * as a known decoration.
 *
 * # Scope: CSS only, deliberately
 *
 * A `data:` URI inside a JS string is not necessarily an image request — it can
 * be a fixture, a comparison value, or dead vendor code. In CSS, `url(data:…)`
 * IS the request. Rewriting only what will actually be fetched keeps this from
 * silently changing library behaviour it does not understand.
 */
function emitCssDataImages(): Plugin {
  const EXT: Record<string, string> = {
    "image/png": "png",
    "image/jpeg": "jpg",
    "image/gif": "gif",
    "image/webp": "webp",
    "image/svg+xml": "svg",
  };
  return {
    name: "myne-emit-css-data-images",
    // `generateBundle`, not `transform`: by this point Vite has already merged
    // and minified the CSS, so there is one pass over the final bytes rather
    // than one per source file — and no chance of a later step re-inlining what
    // this just extracted.
    generateBundle(_options, bundle) {
      const emitted = new Map<string, string>();
      for (const file of Object.values(bundle)) {
        if (file.type !== "asset" || !file.fileName.endsWith(".css")) continue;
        const css = String(file.source);
        const emit = (ext: string, bytes: Buffer, key: string): string => {
          let name = emitted.get(key);
          if (name === undefined) {
            // Deduplicated by payload: the checkerboard appears seven times in
            // one stylesheet, and seven identical files would be seven requests
            // for one image.
            const ref = this.emitFile({
              type: "asset",
              name: `inline-${ext === "svg" ? "svg" : "img"}.${ext}`,
              source: bytes,
            });
            name = this.getFileName(ref);
            emitted.set(key, name);
          }
          return `url("/${name}")`;
        };
        let next = css.replace(
          /url\((["']?)data:(image\/[a-z+]+);base64,([A-Za-z0-9+/=]+)\1\)/g,
          (whole, _q, mime: string, b64: string) => {
            const ext = EXT[mime];
            if (ext === undefined) return whole; // unknown type: leave it alone
            return emit(ext, Buffer.from(b64, "base64"), `b64:${b64}`);
          },
        );
        // The non-base64 form, which the pass above deliberately does not match
        // and which the drawing stylesheet also uses: `url("data:image/svg+xml,
        // <svg …>")`, with the payload's own quotes CSS-escaped as `\"`. Handled
        // separately rather than by widening the first regex, because the
        // terminator is different — a raw SVG contains `)` and `,` freely, so it
        // is bounded by the CLOSING QUOTE, not by the first `)`.
        next = next.replace(
          /url\((["'])data:(image\/svg\+xml),((?:\\.|(?!\1)[^\\])*)\1\)/g,
          (_whole, _q, _mime: string, payload: string) => {
            // Undo the CSS string escaping, then percent-decode: both are
            // present in the vendored form (`\"` for quotes, `%23` for `#`).
            const unescaped = payload.replace(/\\(.)/g, "$1");
            let svg: string;
            try {
              svg = decodeURIComponent(unescaped);
            } catch {
              svg = unescaped; // not percent-encoded; take it verbatim
            }
            return emit("svg", Buffer.from(svg, "utf8"), `svg:${svg}`);
          },
        );
        if (next !== css) file.source = next;
      }
    },
  };
}


// Vite config for the `web/` target (phase3-web-client task 7).
//
// Root is `web/`, so the emitted document is `web/dist/index.html` and the dev
// server serves it at `/`. The shared tree it compiles (`../src/`) lives above
// that root, which Vite allows on the build side and which `server.fs.allow`
// permits on the dev side. `publicDir` points back at the repository's shared
// `public/` so both clients serve the same fonts, marks and Excalidraw assets
// from one place.
//
// The one substitution that makes this a different client is the platform
// seam. `src/` reaches its host through `src/platform/*` and nothing else
// (enforced by `scripts/check-platform-seam.mjs`), so redirecting that one
// directory to `web/src/platform/*` is the whole of the fork.
//
// Why a resolver plugin and not `resolve.alias`: call sites import the seam by
// RELATIVE path (`../platform/core`, `../../platform/event`, …), whose
// specifier text differs per file depth, so there is no single string or safe
// regex to alias on. Resolving first and then redirecting by resolved path is
// exact — it cannot match a coincidentally-similar specifier in a dependency,
// and it needs no cooperation from the files being redirected.


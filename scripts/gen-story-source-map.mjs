#!/usr/bin/env node
// gen-story-source-map.mjs, generate the surface -> source reference the rail
// shows (myne-md/myne#845).
//
// The map is GENERATED rather than hand-written for the same reason the
// Foundations specimens are: a hand-kept path per surface is a second copy of
// where the file lives, and it drifts the first time a module moves. It reuses
// the coverage guard's own enumeration, so the two cannot disagree about which
// surfaces exist.
//
// Writes `stories/src/source-map.ts` (a TS module, not JSON, so the catalogue's
// tsconfig needs no `resolveJsonModule`).
//
// `--check` GATES the committed file against a fresh generation, the contract
// `check-twin-inventory.mjs` and `check-i18n-coverage.mjs` already follow. It
// exists because the first version of this generator had NO caller and no gate:
// the branch that added it moved `QuickPicker` and `Select` and left the
// committed map pointing at the old lines, and nothing reported it while the
// rail rendered a "Show on GitHub" link to the wrong line (myne-md/myne#847
// review).

import { readFileSync, writeFileSync, existsSync } from "node:fs";
import { join } from "node:path";
import { enumerateSurfaces } from "./check-story-coverage.mjs";

const ROOT = new URL("..", import.meta.url).pathname.replace(/\/$/, "");
const OUT = join(ROOT, "stories/src/source-map.ts");

/** The line the module is declared on, or 1 when the shape is not recognised. */
function declarationLine(text, name) {
  const lines = text.split("\n");
  const patterns = [
    new RegExp(`^\\s*export\\s+function\\s+${name}\\b`),
    new RegExp(`^\\s*export\\s+const\\s+${name}\\b`),
    new RegExp(`^\\s*export\\s+class\\s+${name}\\b`),
    new RegExp(`^\\s*export\\s+default\\b`),
  ];
  for (let i = 0; i < lines.length; i += 1) {
    if (patterns.some((re) => re.test(lines[i]))) return i + 1;
  }
  return 1;
}

/**
 * The whole generated file, as a string.
 *
 * Pure over the surface enumeration, so `--check` and a real write cannot
 * disagree about what "generated" means.
 */
export function generate() {
  const surfaces = enumerateSurfaces();
  const entries = [];
  for (const [name, file] of [...surfaces.entries()].sort((a, b) => a[0].localeCompare(b[0]))) {
    let line = 1;
    try {
      line = declarationLine(readFileSync(join(ROOT, file), "utf8"), name);
    } catch {
      // A surface whose file cannot be read keeps line 1 rather than failing the
      // generation: the reference is help, not a gate.
    }
    entries.push(`  ${JSON.stringify(name)}: { file: ${JSON.stringify(file)}, line: ${line} },`);
  }

  return `// GENERATED by scripts/gen-story-source-map.mjs. Do not hand-edit.
//
// Which file (and line) declares each surface, so the rail can show a source
// reference and link to it (myne-md/myne#845). Regenerate after moving a module.

export interface SourceReference {
  /** Repository-relative path, e.g. \`src/components/primitives/Button.tsx\`. */
  file: string;
  /** The 1-based line the module is declared on. */
  line: number;
}

export const SOURCE_MAP: Record<string, SourceReference> = {
${entries.join("\n")}
};
`;
}

const invokedDirectly =
  process.argv[1] !== undefined && import.meta.url.endsWith(process.argv[1].split("/").pop());

if (invokedDirectly) {
  const generated = generate();
  if (process.argv.includes("--check")) {
    if (!existsSync(OUT)) {
      console.error(
        "gen-story-source-map: FAIL: stories/src/source-map.ts does not exist; run `node scripts/gen-story-source-map.mjs`",
      );
      process.exit(1);
    }
    const committed = readFileSync(OUT, "utf8");
    if (committed !== generated) {
      const stale = committed
        .split("\n")
        .filter((line, index) => generated.split("\n")[index] !== line)
        .slice(0, 5);
      console.error(
        "gen-story-source-map: FAIL: the committed map is stale; run `node scripts/gen-story-source-map.mjs`",
      );
      for (const line of stale) console.error(`  ${line.trim()}`);
      process.exit(1);
    }
    console.log("gen-story-source-map: up to date");
  } else {
    writeFileSync(OUT, generated);
    const count = generated.split("\n").filter((line) => line.trim().startsWith('"')).length;
    console.log(`source map written: ${count} surfaces -> stories/src/source-map.ts`);
  }
}

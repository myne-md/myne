#!/usr/bin/env sh
# Post-deploy smoke gate for the hosted web client (MYND-574 task 112).
#
#   scripts/web-smoke.sh <origin> <expected-sync-origin> [expected-commit]
#   scripts/web-smoke.sh https://app.example.com https://sync.myne.md "$CI_COMMIT_SHA"
#
# Runs AFTER the deploy, against the PUBLIC origin over TLS — not against the
# container on loopback. The difference is the whole point: every failure this
# gate exists to catch lives between the container and the browser. A host proxy
# that drops a response header, a certificate that did not renew, a stack that
# came up on the previous image — all of them are invisible from inside the
# container and all of them break the client.
#
# What it refuses to do is decide whether a header's VALUE is good. The policy
# is generated by the container from its configured sync origin (task 50) and
# unit-tested at its source (`tests/web/csp.test.ts`); re-deriving the expected
# string here would create a second definition of the policy that drifts from
# the first. This asks the deployment questions instead: is the header present,
# does the CSP name the sync origin this deployment was configured for, and is
# the bundle the commit we just built.
#
# Exit non-zero on the first failing assertion so the pipeline stops with the
# reason on stdout. A failing smoke leaves the PREVIOUS container running —
# nothing here rolls anything back, because `docker compose up -d` has already
# replaced it by the time this runs; see `operations/runbooks/web-client-deploy.md`
# §3 for the rollback the operator performs when this goes red.
set -eu

ORIGIN="${1:?usage: web-smoke.sh <origin> <expected-sync-origin> [expected-commit]}"
SYNC_ORIGIN="${2:?expected sync origin required}"
EXPECT_COMMIT="${3:-}"

fail() {
  echo "SMOKE FAIL: $1" >&2
  exit 1
}

echo "== smoke: ${ORIGIN} (sync origin ${SYNC_ORIGIN}) =="

# ── the entry document, with its headers ────────────────────────────────────
# `-D-` writes headers to stdout; the body is discarded. `--fail` is deliberately
# NOT used: a non-2xx is reported by the status check below with its actual code,
# which is more useful than curl's generic failure.
HEAD_FILE="$(mktemp)"
BODY_FILE="$(mktemp)"
trap 'rm -f "$HEAD_FILE" "$BODY_FILE"' EXIT

STATUS="$(curl -sS -o "$BODY_FILE" -D "$HEAD_FILE" -w '%{http_code}' "${ORIGIN}/")" \
  || fail "could not reach ${ORIGIN}/ (TLS or DNS failure — curl exited non-zero)"
[ "$STATUS" = "200" ] || fail "${ORIGIN}/ answered ${STATUS}, expected 200"

# Header names are case-insensitive on the wire, so match case-insensitively.
header_value() {
  awk -v want="$(echo "$1" | tr 'A-Z' 'a-z')" '
    BEGIN { FS=": " }
    { line = $0; sub(/\r$/, "", line) }
    {
      split(line, kv, ": ")
      k = tolower(kv[1])
      if (k == want) { sub(/^[^:]*: /, "", line); print line }
    }
  ' "$HEAD_FILE"
}

require_header() {
  v="$(header_value "$1")"
  [ -n "$v" ] || fail "response header $1 is MISSING — the deployment lost it between the container and the browser"
  echo "   ok  $1"
}

# The five that carry the client's security posture. Losing any of them in
# production is invisible to the operator and fatal to the client: without COOP
# and COEP the page is not cross-origin isolated, without the CSP the bundle is
# not the only code that can run, without CORP its assets are readable
# cross-origin, and without HSTS a first request can be downgraded.
require_header "Cross-Origin-Opener-Policy"
require_header "Cross-Origin-Embedder-Policy"
require_header "Cross-Origin-Resource-Policy"
require_header "Content-Security-Policy"
require_header "Strict-Transport-Security"

# ── the CSP names THIS deployment's sync origin ─────────────────────────────
# A client whose `connect-src` does not name its sync server cannot sync at all,
# and on web sync is required — so this is a total outage that serves a
# perfectly good-looking page. The failure mode it guards is a stack brought up
# with the wrong `MYNE_SYNC_ORIGIN`, which nothing else notices.
CSP="$(header_value "Content-Security-Policy")"
CONNECT_SRC="$(printf '%s' "$CSP" | tr ';' '\n' | grep -i 'connect-src' || true)"
[ -n "$CONNECT_SRC" ] || fail "CSP has no connect-src directive at all"
case "$CONNECT_SRC" in
  *"$SYNC_ORIGIN"*) echo "   ok  CSP connect-src names ${SYNC_ORIGIN}" ;;
  *) fail "CSP connect-src does not name ${SYNC_ORIGIN} — got: ${CONNECT_SRC}" ;;
esac

# ── operational endpoints (task 111) ────────────────────────────────────────
HEALTH="$(curl -sS -o /dev/null -w '%{http_code}' "${ORIGIN}/healthz")"
[ "$HEALTH" = "200" ] || fail "/healthz answered ${HEALTH}, expected 200"
echo "   ok  /healthz 200"

# The runtime configuration the CLIENT reads (task 50). Checked against the same
# expected origin the CSP was checked against, because those two values coming
# apart is a client that makes requests its own policy blocks — and because a
# deployment that serves no config at all reaches the password screen and fails
# there with "no sync server configured", which is exactly how this was found.
CONFIG_JSON="$(curl -sS "${ORIGIN}/config.json")" || fail "could not fetch /config.json"
CONFIG_ORIGIN="$(printf '%s' "$CONFIG_JSON" | sed -n 's/.*"sync_origin"[[:space:]]*:[[:space:]]*"\([^"]*\)".*/\1/p')"
[ "$CONFIG_ORIGIN" = "$SYNC_ORIGIN" ] \
  || fail "/config.json names '${CONFIG_ORIGIN}', expected ${SYNC_ORIGIN} — the client would talk to the wrong server, or to none"
echo "   ok  /config.json names ${SYNC_ORIGIN}"

VERSION_JSON="$(curl -sS "${ORIGIN}/version.json")" || fail "could not fetch /version.json"
SERVED_COMMIT="$(printf '%s' "$VERSION_JSON" | sed -n 's/.*"commit"[[:space:]]*:[[:space:]]*"\([^"]*\)".*/\1/p')"
SERVED_HASH="$(printf '%s' "$VERSION_JSON" | sed -n 's/.*"bundle_hash"[[:space:]]*:[[:space:]]*"\([^"]*\)".*/\1/p')"
[ -n "$SERVED_COMMIT" ] || fail "/version.json carries no commit field"
[ -n "$SERVED_HASH" ] || fail "/version.json carries no bundle_hash field"
echo "   ok  serving commit ${SERVED_COMMIT} (${SERVED_HASH})"

# The staleness check, and the reason the deploy is observable at all: without
# it a deploy that silently failed to replace the container passes every other
# assertion above, because the OLD bundle answers them all correctly.
if [ -n "$EXPECT_COMMIT" ]; then
  [ "$SERVED_COMMIT" = "$EXPECT_COMMIT" ] \
    || fail "stale deploy — serving ${SERVED_COMMIT}, expected ${EXPECT_COMMIT}"
  echo "   ok  served commit matches the build"
else
  echo "   -- no expected commit given, staleness not checked"
fi

# ── SPA fallback ────────────────────────────────────────────────────────────
# Routes are path segments (`/editor/<uuid>`, not `?note=`), so an origin
# without the fallback answers every bookmark and every reload-in-the-editor
# with a 404 — and nothing in the client can detect that. Task 109's own note.
DEEP="$(curl -sS -o /dev/null -w '%{http_code}' "${ORIGIN}/editor/00000000-0000-7000-8000-000000000000")"
[ "$DEEP" = "200" ] || fail "deep link answered ${DEEP} — the SPA fallback is missing at this origin"
echo "   ok  SPA fallback serves the entry document on a deep link"

echo "== smoke passed =="

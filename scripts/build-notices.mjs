/**
 * Build-time notices for the desktop/web artefact.
 *
 * The root LICENSE and the generated third-party notice must ship beside the
 * built bundle. Vite copies public/ into dist/, but the root licence is not
 * under public/ and used to be left out of the artefact entirely.
 */
import { copyFileSync, existsSync, mkdirSync, statSync } from "node:fs";
import { join } from "node:path";

const root = process.cwd();
const dist = join(root, "dist");
mkdirSync(dist, { recursive: true });

const copies = [
  ["LICENSE", "LICENSE"],
  ["public/THIRD-PARTY-LICENSES.txt", "THIRD-PARTY-LICENSES.txt"],
];
for (const [from, to] of copies) {
  const src = join(root, from);
  if (!existsSync(src)) {
    console.error(`build-notices: missing ${from}`);
    process.exit(1);
  }
  copyFileSync(src, join(dist, to));
  console.log(`build-notices: ${to} (${statSync(src).size} bytes)`);
}

// The Rust notice is generated by the `notices` CI job, which has cargo. A
// local frontend build can still copy one if it was generated already.
const rustNotice = join(root, "THIRD-PARTY-LICENSES-rust.txt");
if (existsSync(rustNotice)) {
  copyFileSync(rustNotice, join(dist, "THIRD-PARTY-LICENSES-rust.txt"));
  console.log("build-notices: THIRD-PARTY-LICENSES-rust.txt");
}

/**
 * Generate a third-party licence notice for the Rust workspace.
 *
 * `cargo metadata` is the source of truth: it is the same resolver the build
 * uses, so a dependency that is added but not noticed shows up here. The
 * notice lists every non-workspace package with its licence expression and
 * includes the upstream licence text when the crate ships one. It is generated
 * rather than hand-maintained, and the notices CI job compares/regenerates it.
 */
import { execFileSync } from "node:child_process";
import { existsSync, mkdirSync, readFileSync, readdirSync, statSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";

const outArg = process.argv.indexOf("--out");
const out = join(process.cwd(), outArg !== -1 ? process.argv[outArg + 1] : "dist/THIRD-PARTY-LICENSES-rust.txt");
mkdirSync(dirname(out), { recursive: true });

const metadata = JSON.parse(
  execFileSync("cargo", ["metadata", "--format-version", "1", "--locked"], {
    encoding: "utf8",
    maxBuffer: 256 * 1024 * 1024,
  }),
);
const workspace = new Set(metadata.workspace_members);
const packages = metadata.packages
  .filter((pkg) => !workspace.has(pkg.id))
  .sort((a, b) => `${a.name}@${a.version}`.localeCompare(`${b.name}@${b.version}`));

const LICENCE_FILE = /^(licen[cs]e|copying|notice)(\..*)?$/i;
const seen = new Set();
const chunks = [];
for (const pkg of packages) {
  const key = `${pkg.name}@${pkg.version}`;
  if (seen.has(key)) continue;
  seen.add(key);

  const lines = [`${pkg.name} ${pkg.version}`];
  if (pkg.license) lines.push(`License: ${pkg.license}`);
  if (pkg.repository) lines.push(`Repository: ${pkg.repository}`);
  if (pkg.source) lines.push(`Source: ${pkg.source}`);
  lines.push("");

  let text = null;
  const dir = pkg.manifest_path ? dirname(pkg.manifest_path) : null;
  if (dir && existsSync(dir)) {
    const candidate = readdirSync(dir).find((name) => LICENCE_FILE.test(name));
    if (candidate) {
      const file = join(dir, candidate);
      if (statSync(file).isFile()) {
        text = readFileSync(file, "utf8").trim();
        lines.push(`--- ${candidate} ---`, text, "");
      }
    }
  }
  if (!text) lines.push("(No licence file is shipped in the crate archive; see the declared licence expression.)", "");
  chunks.push(lines.join("\n"));
}

const header = [
  "Myne — Third-Party Licenses (Rust workspace)",
  "================================================================",
  "",
  "Generated by scripts/gen-rust-third-party-licenses.mjs from",
  "`cargo metadata --format-version 1 --locked`. Do not edit by hand.",
  `Packages: ${seen.size}`,
  "",
].join("\n");
writeFileSync(out, header + chunks.join("\n") + "\n");
console.log(`gen-rust-third-party-licenses: ${seen.size} packages -> ${out}`);

// Real-app UI screenshots for before/after PR review (`node scripts/shot-ai-panels.mjs`).
//
// Every UI PR in this repo carries before/after images. These are NOT mockups:
// both shots render the real components with the real styles in real Chromium.
//
//   --which mobile|desktop|both   what to shoot (default: both)
//   --mobile-out <path>           mobile PNG path (default: /tmp/myne-mobile-ai.png)
//   --desktop-out <path>          desktop PNG path (default: /tmp/myne-desktop-ai.png)
//
// Before/after comes from running twice: shoot the branch, `git stash push`
// the UI files, shoot again, `git stash pop`. The script only ever shoots the
// current working tree.
//
// How each lane works (full reasoning: `dev-notes/ui-screenshots.md`):
// - desktop: the story catalogue (`pnpm stories`, port 1423) mounts the real
//   `AiChatTab` through its ONE fake-IPC host. The shot navigates to the
//   `ai-panel/chat/default` story and screenshots the stage. This replaced a
//   per-shot temp vite config whose resolveId plugin stubbed IPC modules, so
//   there is now a single fake-IPC host for the desktop AI panel
//   (myne-md/myne#832 task 14).
// - mobile: a generated Playwright flow spec drives the REAL mobile app served
//   by its vite dev server with mock Tauri IPC (`mobile/tests/flow-logic/`).
//
// Zero dependencies beyond what the repo already installs (vite at the root,
// `@playwright/test` in the mobile workspace).
import { spawn } from "node:child_process";
import { rmSync, writeFileSync } from "node:fs";
import { tmpdir } from "node:os";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const MOBILE_DIR = join(ROOT, "mobile");
const STORIES_PORT = 1423;
// Overridable, because `dev-notes/ui-screenshots.md` tells a caller to "point
// STORIES_STORY at it" and the constant was the only way to do that, which meant
// editing this file to shoot any surface but the AI panel. The default is
// unchanged, so the documented AI-panel invocation behaves exactly as before.
const STORIES_STORY = process.env.STORIES_STORY ?? "ai-panel/chat/default";

function arg(name, fallback) {
  const i = process.argv.indexOf(name);
  return i === -1 ? fallback : (process.argv[i + 1] ?? fallback);
}

function run(cmd, args, opts = {}) {
  return new Promise((resolvePromise, reject) => {
    const child = spawn(cmd, args, { stdio: "pipe", ...opts });
    let out = "";
    child.stdout?.on("data", (d) => {
      out += d;
    });
    child.stderr?.on("data", (d) => {
      out += d;
    });
    child.on("error", reject);
    child.on("close", (code) =>
      code === 0 ? resolvePromise(out) : reject(new Error(`${cmd} exited ${code}\n${out}`)),
    );
  });
}

function waitFor(url, timeoutMs = 60000) {
  const start = Date.now();
  return new Promise((resolvePromise, reject) => {
    const tick = async () => {
      try {
        const res = await fetch(url);
        if (res.ok) return resolvePromise();
      } catch {
        // not up yet
      }
      if (Date.now() - start > timeoutMs) return reject(new Error(`timeout waiting for ${url}`));
      setTimeout(tick, 500);
    };
    tick();
  });
}

// ---------------------------------------------------------------- mobile ---

const MOBILE_SPEC = `// GENERATED by scripts/shot-ai-panels.mjs - do not edit, deleted after the run.
import { test } from "@playwright/test";
import { installMockIpc } from "../mock-ipc";

const A_NOTE = [{ id: "n1", text: "---\\ntitle: Migration\\n---\\n\\nSome notes about it.\\n" }];

test("ai panel shot", async ({ page }) => {
  const errs: string[] = [];
  page.on("pageerror", (e) => errs.push(String(e)));
  await installMockIpc(page, {
    prefs: { ai_enabled: true },
    notes: A_NOTE,
    chats: {
      rows: [{ id: "c1", created_at: 100, title: "Chat", updated_at: 100, version: 1 }],
      payloads: {
        c1: JSON.stringify({
          turns: [{ id: "h1", kind: "text", role: "user", text: "can you translate this note?" }],
        }),
      },
    },
  });
  await page.goto("/");
  await page.getByTestId("notes.row").first().click();
  await page.getByTestId("editor.back").click();
  await page.getByTestId("workspace.tab-chat").click();
  await page.getByTestId("ai.composer-input").fill("can you translate this note to english?");
  await page.waitForTimeout(500);
  await page.screenshot({ path: process.env.SHOT_OUT, fullPage: true });
  if (errs.length > 0) throw new Error("page errors: " + errs.join(" | "));
});
`;

async function shotMobile(out) {
  const spec = join(MOBILE_DIR, "tests/flow-logic/ai/__shots-tmp.flow.ts");
  writeFileSync(spec, MOBILE_SPEC);
  try {
    await run("npx", ["playwright", "test", "--config=playwright.config.ts", "--project=chromium", spec], {
      cwd: MOBILE_DIR,
      env: { ...process.env, SHOT_OUT: out },
    });
  } finally {
    rmSync(spec, { force: true });
  }
  console.log(`mobile shot: ${out}`);
}

// --------------------------------------------------------------- desktop ---
//
// The desktop lane is now the story catalogue: one fake-IPC host (`pnpm stories`),
// and this shot is a thin Playwright navigation to a story URL. The temp preview
// config that used to live here (a resolveId plugin stubbing usePrefs, agent-run,
// ai-capability, chatPersist) is gone.

const SHOT_SCRIPT = `const { chromium } = require(${JSON.stringify(join(MOBILE_DIR, "node_modules", "@playwright", "test"))});
(async () => {
  const browser = await chromium.launch();
  const page = await browser.newPage({ viewport: { width: 1200, height: 1080 } });
  const errors = [];
  page.on("pageerror", (e) => errors.push(String(e)));
  await page.goto("http://localhost:${STORIES_PORT}/#${STORIES_STORY}", { waitUntil: "networkidle" });
  await page.waitForSelector('[data-testid="stories.story"]', { timeout: 20000 });
  await page.waitForTimeout(800);
  if (process.env.SHOT_FULL_PAGE === "1") {
    // For a surface that is position:fixed. The story element contributes no
    // height to its own box, so clipping to it cuts such a surface out of the
    // frame entirely; the whole stage is the only honest view of where it sits.
    // (No backticks in this comment: the script this builds is ONE template
    // literal, and a backtick ends it, which cost a run to rediscover.)
    await page.screenshot({ path: process.env.SHOT_OUT });
  } else {
    await page.locator('[data-testid="stories.story"]').screenshot({ path: process.env.SHOT_OUT });
  }
  if (errors.length > 0) throw new Error("PAGE ERRORS: " + errors.join(" | "));
  console.log("no page errors");
  await browser.close();
})().catch((e) => { console.error(e); process.exit(1); });
`;

async function shotDesktop(out) {
  const script = join(tmpdir(), `shot-desktop-${Date.now()}.cjs`);
  writeFileSync(script, SHOT_SCRIPT);
  const server = spawn("npx", ["vite", "--config", "stories/vite.config.ts"], {
    cwd: ROOT,
    stdio: "ignore",
    detached: true,
  });
  server.unref();
  try {
    await waitFor(`http://localhost:${STORIES_PORT}/`);
    await run(process.execPath, [script], {
      cwd: MOBILE_DIR,
      env: { ...process.env, SHOT_OUT: out },
    });
  } finally {
    try {
      process.kill(-server.pid);
    } catch {
      server.kill();
    }
    rmSync(script, { force: true });
  }
  console.log(`desktop shot: ${out}`);
}

const which = arg("--which", "both");
const mobileOut = resolve(arg("--mobile-out", "/tmp/myne-mobile-ai.png"));
const desktopOut = resolve(arg("--desktop-out", "/tmp/myne-desktop-ai.png"));

if (!["mobile", "desktop", "both"].includes(which)) {
  console.error("usage: node scripts/shot-ai-panels.mjs [--which mobile|desktop|both] [--mobile-out P] [--desktop-out P]");
  process.exit(1);
}

try {
  if (which === "mobile" || which === "both") await shotMobile(mobileOut);
  if (which === "desktop" || which === "both") await shotDesktop(desktopOut);
  console.log("done");
} catch (e) {
  console.error(String(e?.message ?? e));
  process.exit(1);
}

//! Shared, host-coupled-but-platform-agnostic Tauri plugin cores.
//!
//! Each plugin is a self-contained module with its own commands, state, and
//! error type. The plugin-pattern over flat-app-level commands is documented
//! in `private-companion/sessions/design/2026-04-28-vault-creation-flow.md` Q8.3 —
//! domain isolation enforced at compile time.
//!
//! These cores are shared between the desktop (`myne-desktop`) and future
//! mobile clients. Remaining desktop-only plugins (search, spell, …) stay in
//! the desktop crate and attach through the `hooks::VaultLifecycleHooks`
//! seam rather than living here. The `sync` engine was extracted into this
//! shared core (decisions.md 2026-07-07); each client keeps only the thin
//! `init()`/`generate_handler!`/capability shim.

/// Agentic note editing (myne-md/myne#529): the run, its approved scope, the
/// tools the model may call, the anchored edit format and the apply. The AI
/// engine stays in each client; this core depends on a narrow generation trait
/// the host implements, which is what lets mobile inherit the loop.
pub mod agent;
pub mod attachments;
// ── plugins with no browser meaning at all (phase3-web-client) ───────────────
//
// Gated OUT of the wasm build rather than ported, because the wasm-portability
// assessment's verdict for each is `cannot-exist-in-browser` and the web
// capability set already excludes them by decision, not by backlog
// (`decisions.md` 2026-07-26, "Web capability set"):
//
//   captures      — the watch dictates a note over WatchConnectivity; there is
//                   no watch and no OS queue in a browser tab.
//   export        — writes a vault markdown tree to an OS path the user picks
//                   through a native Save-As dialog. Backup export/restore is
//                   absent on web by decision, and a browser has no path to
//                   write to.
//   share_import  — drains files handed over by the OS share sheet. A page has
//                   no share sheet.
//
// Gating whole modules is the honest shape here: a ported command that then
// always returns "unsupported" would be dead code pretending to be a feature.
// The UI's answer is omission (task 27), not a disabled affordance.
#[cfg(all(feature = "tauri-ipc", not(target_arch = "wasm32")))]
pub mod captures;
pub mod chats;

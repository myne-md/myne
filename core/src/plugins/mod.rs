// ── phrase-recovery: compiled for BOTH targets since 2026-08-15 ─────────────
//
// This module was gated out of the wasm build entirely. `decisions.md`
// 2026-07-26 made it normative that the 24-word BIP-39 phrase is "never
// generated by, displayed by, or typed into served code", and `recover_with_
// phrase` / `complete_recovery` are where a phrase gets typed — so the module
// was cut at the `cfg`, not merely left undispatched, because the acceptance
// criterion was "absent from the web build, not merely unused".
//
// `decisions.md` **2026-08-15** reverses that rule: phrase recovery ships on
// the web client. The gate is therefore gone, and what replaces it is narrower
// and stated where it is enforced rather than here — the ENROLMENT credential
// stays out of the served bundle (`web/vite.config.ts` substitution plus
// `scripts/check-web-no-phrase.mjs` over the built artefact), and
// `plugin:sync|sync_enroll` refuses the recovery credential kind at the
// dispatcher's last door.
//
// `protocol.md` §7 has not changed and is why the remaining restriction is
// worth code rather than review: the phrase is a permanent credential with no
// rotation command anywhere in this repo, so a leaked one has no in-app remedy.
pub mod vault_recover;

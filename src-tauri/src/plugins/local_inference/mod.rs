/// The scoped capability granted to the main window, added at RUNTIME (task 6).
///
/// It is NOT a static `capabilities/*.json` entry on purpose: the whole plugin
/// is behind the default-off `local-inference` feature, and a static entry
/// referencing `local-inference:default` would make the feature-OFF build fail
/// on an unresolved permission. Adding it at runtime — only when this
/// feature-gated plugin is registered — keeps the default build clean. Grants
/// ONLY `local-inference:default` (infer + embed); no core/fs/dialog/clipboard/
/// network. The `allow-infer` / `allow-embed` command permissions are
/// auto-generated by the `CARGO_FEATURE_LOCAL_INFERENCE`-gated `InlinedPlugin`
/// in `build.rs`; referencing them directly (rather than a toml-defined
/// `default` set) means there is NO `permissions/local-inference/` directory to
/// be scanned + dangle in the feature-OFF build.
const LOCAL_INFERENCE_CAPABILITY: &str = r#"{
  "identifier": "local-inference",
  "description": "On-device AI inference + retrieval + grounded Q&A commands (infer/embed/semantic_search/ask) for the main window; no core/fs/dialog/clipboard/network.",
  "windows": ["main"],
  "permissions": ["local-inference:allow-infer", "local-inference:allow-embed", "local-inference:allow-semantic-search", "local-inference:allow-ask", "local-inference:allow-chat-stream", "local-inference:allow-chat-stop", "local-inference:allow-transcribe", "local-inference:allow-read-transcript", "local-inference:allow-suggest-tags", "local-inference:allow-tag-model-available", "local-inference:allow-set-model-path", "local-inference:allow-get-model-path"]
}"#;

/// Best-effort zeroize + reset of the in-RAM AI vector store on lock teardown
/// (semantic-search-qa task 2), the twin of the `vault_indices` teardown fn.
/// Resolves the app-managed `LocalInferenceVectorState` and wipes its
/// plaintext-derived embeddings and `content_nonce` manifest. Wired into every
/// slot-drop site so the store never outlives the slot: manual `vault_lock`,
/// idle auto-lock, `vault_delete`, and credential-rotation relock. Sync and
/// infallible; a missing managed state is a silent no-op.
pub fn zeroize_ai_vectors<R: Runtime>(app: &tauri::AppHandle<R>) {
    // Abort any in-flight streaming chat generation first (conversational-ai-chat
    // task 4/12): the chat transcript is RAM-only and dropped on lock (the
    // frontend `clearChat` wipe), so a generation must not keep running — holding
    // the compute lock — or emitting into a torn-down transcript after the vault
    // locks. The publish-guarded `guarded_on_token` sees the flag and breaks.
    if let Some(cancel) = app.try_state::<cancel::CancelToken>() {
        cancel.cancel();
    }
    if let Some(state) = app.try_state::<vector_store::LocalInferenceVectorState>() {
        state.clear();
    }
}

/// Construct the `local-inference` plugin.
///
/// Manages the [`state::LocalInferenceState`] engine singleton and the
/// [`vector_store::LocalInferenceVectorState`] RAM store, binds the
/// `infer`/`embed` `#[tauri::command]`s, and adds the scoped
/// [`LOCAL_INFERENCE_CAPABILITY`] at runtime. Only reachable when the
/// `local-inference` feature is enabled.
pub fn init<R: Runtime>() -> TauriPlugin<R> {
    Builder::<R>::new("local-inference")
        .invoke_handler(tauri::generate_handler![
            commands::infer,
            commands::embed,
            commands::semantic_search,
            commands::ask,
            commands::chat_stream,
            commands::chat_stop,
            commands::transcribe,
            commands::read_transcript,
            commands::suggest_tags,
            commands::tag_model_available,
            commands::set_model_path,
            commands::get_model_path
        ])
        .setup(|app, _api| {
            // Engine selection is a COMPILE-TIME choice, not a runtime hook:
            //   - production (`--features local-inference`) → the Candle engine,
            //     lazy-loading the user's side-loaded models; no model set →
            //     `NotReady` per call (the UI shows the error state).
            //   - E2E (`--features local-inference-stub`) → the deterministic
            //     `StubEngine`, so the tauri-driver flow-suite gets stable output
            //     (`stub-infer: …` / a fixed embedding) without shipping a model
            //     into the repo. This is a feature-flagged E2E *build* variant —
            //     the audited production bundle never enables it.
            #[cfg(feature = "local-inference-stub")]
            let engine: std::sync::Arc<dyn engine::Engine> =
                std::sync::Arc::new(engine::StubEngine);
            #[cfg(not(feature = "local-inference-stub"))]
            let engine: std::sync::Arc<dyn engine::Engine> = {
                let base = crate::paths::app_data_dir(app)
                    .unwrap_or_else(|_| std::path::PathBuf::from("."));
                // The bundled default transcription model (voice-to-text,
                // MYND-270), resolved from the Tauri resource dir — `None` when
                // none ships (an AI-free `--no-default-features` build, or a
                // checkout whose LFS model blob was not fetched), leaving STT
                // side-load-only.
                let resource_dir = app.path().resource_dir().ok();
                let bundled_transcription = resource_dir
                    .as_deref()
                    .and_then(model_store::bundled_transcription_model);
                // The bundled auto-tag task-model (MYND-651). Same
                // present-or-nothing resolution, but with no side-load fallback:
                // `None` means this build simply has no auto-tag.
                let bundled_tag = resource_dir
                    .as_deref()
                    .and_then(model_store::bundled_tag_model);
                std::sync::Arc::new(
                    engine_candle::CandleEngine::new(base)
                        .with_bundled_transcription(bundled_transcription)
                        .with_bundled_tag_model(bundled_tag),
                )
            };
            app.manage(state::LocalInferenceState::new(engine));
            app.manage(vector_store::LocalInferenceVectorState::default());
            // Shared cancel flag for the streaming chat surface (task 4/5): the
            // `chat_stream` generation observes it; `chat_stop` and the vault-
            // lock teardown (task 12) set it.
            app.manage(cancel::CancelToken::default());
            // Compute-lock priority register (auto-tag, MYND-651 task 4): the
            // user-initiated commands register here for the length of their
            // call, and the background tag pass stands down while any of them
            // is pending. The single `compute` mutex cannot express an ordering
            // on its own — this is that ordering.
            app.manage(compute_priority::ComputePriority::default());
            app.add_capability(LOCAL_INFERENCE_CAPABILITY)?;
            Ok(())
        })
        .build()
}

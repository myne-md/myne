//! `local-inference` plugin — on-device LLM + embedding engine behind an
//! [`Engine`] trait (local-ai epic, MYND-406).
//!
//! **Default-off cargo feature (`local-inference`, SYNC-5).** The whole module
//! is gated in `plugins/mod.rs` and its registration in `lib.rs`, so the
//! default auditable binary carries zero AI symbols, no `local-inference`
//! command, and no capability entry — the reproducible-build / single-
//! `Cargo.lock` (TB9) surface is byte-unchanged unless someone opts in.
//!

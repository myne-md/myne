//! How the host talks to the `myne-tor` sidecar: the config file it is given,
//! the argv it is launched with, and the one stderr line that means
//! "bootstrapped".
//!
//! All three are pure functions over strings and paths so the shape of the
//! invocation is asserted by unit tests rather than discovered at runtime on a
//! user's machine.
//!
//! ## Why a config file and not just `-o` overrides
//!
//! arti reads `~/.config/arti/arti.toml` (and the platform equivalents) by
//! default, and `tor_config`'s `try_from_cmdline` skips that default list
//! entirely as soon as **one** `-c` is passed. Handing the sidecar our own
//! config is therefore what stops a pre-existing (or hostile) user-level arti
//! config from redirecting the proxy, adding a log file full of connection
//! targets, or enabling a bridge we never asked for. It is also auditable: the
//! posture the sidecar runs under is a file a reviewer can read, not an argv we
//! assembled.

use std::ffi::OsString;
use std::path::Path;

/// The one arti log line the readiness gate keys on.
///
/// arti emits it at `INFO` from `arti::subcommands::proxy` immediately after
/// `client.bootstrap()` resolves. It is the only signal this build exposes —
/// arti's RPC surface is a feature we deliberately do not compile in — so the
/// config file below pins the console log level to `info`. Lowering that level
/// would silence readiness and leave the sidecar stuck in `Starting` forever;
/// the config's own comment says so at the line that would do it.
const BOOTSTRAP_MARKER: &str = "Sufficiently bootstrapped";

/// Does this line of the sidecar's stderr mean "bootstrap finished"?
///
/// Deliberately narrow, and a predicate rather than a classifier: the host does
/// not mirror arti's log stream into its own. arti logs connection targets at
/// `info`, and re-emitting them would put the very hostnames Tor exists to hide
/// into Myne's log sink (`src-tauri/AGENTS.md` secret-handling discipline).
/// Every other line is read and dropped.
pub fn is_bootstrap_line(line: &str) -> bool {
    line.contains(BOOTSTRAP_MARKER)
}

/// The argv for `myne-tor`, minus the program itself.
///
/// `proxy -p <port>` is arti's own CLI (`-p 0` would *disable* the listener, so
/// the caller picks a real port); `-c` pins the config; `-l info` is redundant
/// with the config's `console` setting and stated anyway, because a future
/// config edit that drops it should not silently break readiness detection.
pub fn arti_argv(config_file: &Path, socks_port: u16) -> Vec<OsString> {
    vec![
        OsString::from("proxy"),
        OsString::from("-c"),
        config_file.as_os_str().to_os_string(),
        OsString::from("-l"),
        OsString::from("info"),
        OsString::from("-p"),
        OsString::from(socks_port.to_string()),
    ]
}

/// The `arti.toml` the sidecar is launched with. Rewritten on every start, so
/// it is always the config this build intends rather than whatever an older
/// version left behind.
///
/// What is deliberately absent is as load-bearing as what is present: no
/// `[bridges]`, no `[logging] files`, no `socks_listen` (the port comes from
/// argv, one source of truth), and no `port_info_file` — arti writes that JSON
/// only when the path is non-empty, and we already know the port we asked for.
pub fn arti_config_toml(state_dir: &Path, cache_dir: &Path) -> String {
    format!(
        "\
# Generated by Myne on every sidecar start — edits are overwritten.
#
# This file exists to REPLACE arti's default config search path. Passing any
# `-c` makes arti ignore ~/.config/arti/arti.toml entirely, which is what keeps
# a stray or hostile user-level config from redirecting the proxy, enabling a
# bridge, or writing a log file full of the destinations Tor is hiding.

[storage]
# Cached, not ephemeral: arti's state dir is where entry-guard selections
# persist, and re-picking guards on every launch raises the chance of eventually
# choosing a hostile guard — the trade Tor's guard design exists to avoid. The
# cost is a directory that records this device used Tor, on a disk that already
# holds the device-local toggle saying the same thing.
state_dir = {state}
cache_dir = {cache}

[logging]
# READINESS DEPENDS ON THIS. The host detects a completed bootstrap by matching
# arti's INFO-level \"Sufficiently bootstrapped\" line on stderr; this build does
# not compile arti's RPC surface, so there is no other signal. Raising this to
# \"warn\" leaves the sidecar stuck in Starting and sync paused forever.
console = \"info\"
# No log files. arti logs connection targets, and a file of those on disk is a
# record of exactly what Tor mode is meant to keep off the network.
",
        state = toml_string(state_dir),
        cache = toml_string(cache_dir),
    )
}

/// A path as a TOML basic string. Backslashes (Windows) and quotes are the only
/// characters a path can realistically carry that TOML would misread.
fn toml_string(path: &Path) -> String {
    let s = path.to_string_lossy();
    let escaped = s.replace('\\', "\\\\").replace('"', "\\\"");
    format!("\"{escaped}\"")
}

#[cfg(test)]
mod tests {
    use super::*;
    use std::path::PathBuf;

    #[test]
    fn the_bootstrap_line_arti_actually_emits_is_recognised() {
        // Verbatim from arti 2.5.0 `src/subcommands/proxy.rs`, with the
        // tracing prefix a console subscriber puts in front of it.
        let line = "2026-07-31T12:00:00Z  INFO arti::subcommands::proxy: \
                    Sufficiently bootstrapped; proxy now functional.";
        assert!(is_bootstrap_line(line));
        // The `socks_listen`-empty variant of the same message.
        assert!(is_bootstrap_line("INFO arti: Sufficiently bootstrapped."));
    }

    #[test]
    fn ordinary_progress_lines_are_not_readiness() {
        for line in [
            "INFO arti: Starting Arti 2.5.0",
            "INFO tor_circmgr: We now have enough directory information to build circuits.",
            "INFO arti::socks: Listening on 127.0.0.1:9150.",
            "WARN tor_guardmgr: Guard is unreachable",
            "",
        ] {
            assert!(!is_bootstrap_line(line), "{line:?} is not readiness");
        }
    }

    #[test]
    fn argv_asks_for_a_real_port_our_config_and_info_logging() {
        let argv = arti_argv(&PathBuf::from("/data/tor/arti.toml"), 41234);
        let argv: Vec<String> = argv
            .iter()
            .map(|a| a.to_string_lossy().into_owned())
            .collect();
        assert_eq!(
            argv,
            vec![
                "proxy",
                "-c",
                "/data/tor/arti.toml",
                "-l",
                "info",
                "-p",
                "41234"
            ]
        );
    }

    /// `-p 0` disables arti's SOCKS listener. The port picker never returns 0
    /// (it comes from a bound socket), but the argv builder is where an
    /// accidental default would show up, so pin the encoding.
    #[test]
    fn the_port_is_rendered_as_given_never_defaulted() {
        let argv = arti_argv(&PathBuf::from("/c"), 1);
        assert_eq!(argv.last().unwrap().to_string_lossy(), "1");
    }

    #[test]
    fn the_config_pins_the_dirs_the_log_level_and_nothing_else() {
        let toml = arti_config_toml(
            &PathBuf::from("/data/tor/state"),
            &PathBuf::from("/data/tor/cache"),
        );
        assert!(toml.contains(r#"state_dir = "/data/tor/state""#));
        assert!(toml.contains(r#"cache_dir = "/data/tor/cache""#));
        assert!(toml.contains(r#"console = "info""#));
        // The absences that matter.
        assert!(!toml.contains("[bridges]"));
        // `socks_listen` absent carries TWO meanings, and only the first is
        // obvious: the port comes from argv, one source of truth — AND this is
        // where a listener restriction would be expressed if arti offered one.
        // It does not (`ListenItem` has only IP variants, and `proxy` has no
        // SOCKS auth), so the door is unauthenticated loopback TCP and the
        // residual is recorded in `agent-tooling/docs/threat-model.md` §7 (myne#380). Do not
        // delete this assert while reaching for `socks_listen` — read that
        // entry first.
        assert!(!toml.contains("socks_listen"));
        assert!(!toml.contains("port_info_file"));
        assert!(!toml.contains("files ="));
    }

    /// A Windows app-data path is full of backslashes, and TOML reads `\U` and
    /// friends as escapes — an unescaped one makes arti reject its own config
    /// at startup, which the user would see as "Tor failed" with no cause.
    #[test]
    fn windows_paths_survive_toml_encoding() {
        let toml = arti_config_toml(
            Path::new(r"C:\Users\a\AppData\Roaming\md.myne.desktop\tor\state"),
            Path::new(r"C:\Users\a\cache"),
        );
        assert!(toml.contains(
            r#"state_dir = "C:\\Users\\a\\AppData\\Roaming\\md.myne.desktop\\tor\\state""#
        ));
        assert!(toml.contains(r#"cache_dir = "C:\\Users\\a\\cache""#));
    }

    #[test]
    fn a_quote_in_a_path_cannot_break_out_of_the_toml_string() {
        let toml = arti_config_toml(Path::new(r#"/data/we"ird"#), Path::new("/c"));
        assert!(toml.contains(r#"state_dir = "/data/we\"ird""#));
    }
}

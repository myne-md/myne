/// Whisper FFT window / hop (candle re-exports these; pinned here for the pure
/// [`mel_filters`] math so the filterbank is not silently retuned by a candle
/// constant change).
const N_FFT: usize = whisper::N_FFT; // 400
const SAMPLE_RATE: usize = whisper::SAMPLE_RATE; // 16000
/// Samples in one 30 s decode window (`whisper::N_SAMPLES`, 480000).
const N_SAMPLES: usize = whisper::N_SAMPLES;
/// Mel frames the encoder consumes per 30 s window (`whisper::N_FRAMES`, 3000).
const N_FRAMES: usize = whisper::N_FRAMES;

/// Whisper's 99 language codes, index-aligned to the multilingual model's
/// `<|{code}|>` special tokens (the order the model's language head is trained
/// on). Detection ([`detect_language`]) restricts the first-token logits to the
/// subset of these that resolve in the loaded tokenizer, so an English-only
/// (`.en`) model — which carries no language tokens — simply detects nothing and
/// emits no language token into the prompt.
const LANGUAGES: [&str; 99] = [
    "en", "zh", "de", "es", "ru", "ko", "fr", "ja", "pt", "tr", "pl", "ca", "nl", "ar", "sv", "it",
    "id", "hi", "fi", "vi", "he", "uk", "el", "ms", "cs", "ro", "da", "hu", "ta", "no", "th", "ur",
    "hr", "bg", "lt", "la", "mi", "ml", "cy", "sk", "te", "fa", "lv", "bn", "sr", "az", "sl", "kn",
    "et", "mk", "br", "eu", "is", "hy", "ne", "mn", "bs", "kk", "sq", "sw", "gl", "mr", "pa", "si",
    "km", "sn", "yo", "so", "af", "oc", "ka", "be", "tg", "sd", "gu", "am", "yi", "lo", "uz", "fo",
    "ht", "ps", "tk", "nn", "mt", "sa", "lb", "my", "bo", "tl", "mg", "as", "tt", "haw", "ln",
    "ha", "ba", "jw", "su",
];

/// librosa slaney `hz → mel` (`htk=False`): linear below 1 kHz, log above. f64
/// throughout to match librosa's internal precision before the final f32 cast.
fn hz_to_mel(hz: f64) -> f64 {
    const F_SP: f64 = 200.0 / 3.0;
    const MIN_LOG_HZ: f64 = 1000.0;
    let min_log_mel = MIN_LOG_HZ / F_SP; // 15.0
    let logstep = (6.4f64).ln() / 27.0;
    if hz >= MIN_LOG_HZ {
        min_log_mel + (hz / MIN_LOG_HZ).ln() / logstep
    } else {
        hz / F_SP
    }
}

/// librosa slaney `mel → hz` (the inverse of [`hz_to_mel`]).
fn mel_to_hz(mel: f64) -> f64 {
    const F_SP: f64 = 200.0 / 3.0;
    const MIN_LOG_HZ: f64 = 1000.0;
    let min_log_mel = MIN_LOG_HZ / F_SP; // 15.0
    let logstep = (6.4f64).ln() / 27.0;
    if mel >= min_log_mel {
        MIN_LOG_HZ * (logstep * (mel - min_log_mel)).exp()
    } else {
        F_SP * mel
    }
}

/// The mel filterbank candle's `pcm_to_mel` multiplies each FFT power frame by:
/// a row-major `[n_mels][1 + N_FFT/2]` matrix reproducing
/// `librosa.filters.mel(sr=16000, n_fft=400, n_mels, htk=False, norm="slaney")`.
/// Returned flat (candle indexes `filters[mel * n_fft_bins + bin]`).
pub fn mel_filters(n_mels: usize) -> Vec<f32> {
    let n_fft_bins = 1 + N_FFT / 2; // 201
    let f_max = (SAMPLE_RATE as f64) / 2.0; // 8000

    // FFT bin centre frequencies: linspace(0, sr/2, n_fft_bins).
    let fftfreqs: Vec<f64> = (0..n_fft_bins)
        .map(|k| f_max * (k as f64) / ((n_fft_bins - 1) as f64))
        .collect();

    // Mel band edges in Hz: n_mels + 2 points evenly spaced on the mel scale.
    let n_pts = n_mels + 2;
    let min_mel = hz_to_mel(0.0);
    let max_mel = hz_to_mel(f_max);
    let mel_f: Vec<f64> = (0..n_pts)
        .map(|i| mel_to_hz(min_mel + (max_mel - min_mel) * (i as f64) / ((n_pts - 1) as f64)))
        .collect();
    let fdiff: Vec<f64> = (0..n_pts - 1).map(|i| mel_f[i + 1] - mel_f[i]).collect();

    let mut weights = vec![0.0f32; n_mels * n_fft_bins];
    for m in 0..n_mels {
        // Slaney area normalization: each triangle integrates to a constant.
        let enorm = 2.0 / (mel_f[m + 2] - mel_f[m]);
        for (k, &freq) in fftfreqs.iter().enumerate() {
            let lower = (freq - mel_f[m]) / fdiff[m];
            let upper = (mel_f[m + 2] - freq) / fdiff[m + 1];
            let w = lower.min(upper).max(0.0) * enorm;
            weights[m * n_fft_bins + k] = w as f32;
        }
    }
    weights
}

/// The Whisper control-token ids resolved once against the loaded tokenizer.
/// `sot`/`eot` are required (a tokenizer without them is not a Whisper model →
/// [`EngineError::TranscriptionFailed`]); the rest are optional so both
/// multilingual and English-only (`.en`) tokenizers load.
pub struct WhisperTokens {
    sot: u32,
    eot: u32,
    transcribe: Option<u32>,
    no_timestamps: Option<u32>,
    /// `(language_index_in_LANGUAGES, token_id)` for every language token present.
    languages: Vec<(usize, u32)>,
    /// First timestamp token `<|0.00|>`, if present — everything from here to the
    /// end of the vocab is a timestamp token, suppressed under `no_timestamps`.
    timestamp_begin: Option<u32>,
}

impl WhisperTokens {
    /// Resolve the control tokens from the tokenizer's special vocab.
    pub fn resolve(tk: &Tokenizer) -> Result<Self, EngineError> {
        let id = |s: &str| tk.token_to_id(s);
        let sot = id(whisper::SOT_TOKEN).ok_or_else(|| {
            fmt_stage_fail(
                "transcribe.tokens",
                "tokenizer missing <|startoftranscript|>",
                EngineError::TranscriptionFailed,
            )
        })?;
        let eot = id(whisper::EOT_TOKEN).ok_or_else(|| {
            fmt_stage_fail(
                "transcribe.tokens",
                "tokenizer missing <|endoftext|>",
                EngineError::TranscriptionFailed,
            )
        })?;
        let languages = LANGUAGES
            .iter()
            .enumerate()
            .filter_map(|(i, code)| id(&format!("<|{code}|>")).map(|t| (i, t)))
            .collect();
        Ok(Self {
            sot,
            eot,
            transcribe: id(whisper::TRANSCRIBE_TOKEN),
            no_timestamps: id(whisper::NO_TIMESTAMPS_TOKEN),
            languages,
            timestamp_begin: id("<|0.00|>"),
        })
    }

    /// Whether this is a multilingual model (carries language tokens). An `.en`
    /// model has none → no language detection, no language token in the prompt.
    fn is_multilingual(&self) -> bool {
        !self.languages.is_empty()
    }
}

/// A per-step additive logit bias: `NEG_INFINITY` at every token that must never
/// be emitted (config `suppress_tokens`, the control tokens, and — under
/// `no_timestamps` — every timestamp token), `0.0` elsewhere. Added to the
/// logits before argmax so those tokens can never win. `eot` is intentionally
/// left un-suppressed (it is the stop signal).
fn suppress_bias(
    config: &Config,
    tokens: &WhisperTokens,
    device: &Device,
) -> Result<Tensor, EngineError> {
    let vocab = config.vocab_size;
    let mut bias = vec![0.0f32; vocab];
    let mut suppress = |t: u32| {
        let i = t as usize;
        if i < vocab {
            bias[i] = f32::NEG_INFINITY;
        }
    };
    for &t in &config.suppress_tokens {
        suppress(t);
    }
    // Control tokens must never appear inside the transcript text.
    suppress(tokens.sot);
    if let Some(t) = tokens.transcribe {
        suppress(t);
    }
    if let Some(t) = tokens.no_timestamps {
        suppress(t);
    }
    // Language tokens are prompt-only; never valid inside transcript text.
    for &(_, t) in &tokens.languages {
        suppress(t);
    }
    // Under no_timestamps every timestamp token (>= <|0.00|>) is suppressed.
    if let Some(ts0) = tokens.timestamp_begin {
        for t in ts0..(vocab as u32) {
            suppress(t);
        }
    }
    Tensor::from_vec(bias, vocab, device)
        .map_err(|e| fmt_stage_fail("transcribe.suppress", e, EngineError::TranscriptionFailed))
}

/// Detect the spoken language from a segment's encoder features: one decoder
/// step seeded with just `<|startoftranscript|>`, then argmax over the language-
/// token logits. Returns the winning language token id (to seed the prompt).
fn detect_language(
    model: &mut Whisper,
    tokens: &WhisperTokens,
    audio_features: &Tensor,
    device: &Device,
) -> Result<u32, EngineError> {
    let sot = Tensor::new(&[[tokens.sot]], device)
        .map_err(|e| fmt_stage_fail("transcribe.detect", e, EngineError::TranscriptionFailed))?;
    let ys = model
        .decoder
        .forward(&sot, audio_features, true)
        .map_err(|e| {
            fmt_stage_fail(
                "transcribe.detect.decode",
                e,
                EngineError::TranscriptionFailed,
            )
        })?;
    let logits = model
        .decoder
        .final_linear(&ys)
        .and_then(|l| l.i(0)?.i(0))
        .and_then(|l| l.to_vec1::<f32>())
        .map_err(|e| {
            fmt_stage_fail(
                "transcribe.detect.logits",
                e,
                EngineError::TranscriptionFailed,
            )
        })?;
    // argmax over ONLY the language-token logits.
    let best = tokens
        .languages
        .iter()
        .filter(|&&(_, t)| (t as usize) < logits.len())
        .max_by(|&&(_, a), &&(_, b)| {
            logits[a as usize]
                .partial_cmp(&logits[b as usize])
                .unwrap_or(std::cmp::Ordering::Equal)
        });
    match best {
        Some(&(_, token)) => Ok(token),
        None => Ok(tokens.sot), // unreachable (guarded by is_multilingual)
    }
}

/// Greedily decode one 30 s mel window to token ids (excluding the prompt and the
/// terminating `<|endoftext|>`). `prompt` is the seed sequence
/// (`sot [lang] transcribe no_timestamps`). Bounded by `max_target_positions/2`.
fn decode_segment(
    model: &mut Whisper,
    tokens: &WhisperTokens,
    bias: &Tensor,
    config: &Config,
    audio_features: &Tensor,
    prompt: &[u32],
    device: &Device,
) -> Result<Vec<u32>, EngineError> {
    let sample_len = config.max_target_positions / 2;
    let mut seq: Vec<u32> = prompt.to_vec();
    let prompt_len = seq.len();

    for step in 0..sample_len {
        let input = Tensor::new(seq.as_slice(), device)
            .and_then(|t| t.unsqueeze(0))
            .map_err(|e| {
                fmt_stage_fail(
                    "transcribe.decode.input",
                    e,
                    EngineError::TranscriptionFailed,
                )
            })?;
        // Full sequence each step: self-attention recomputes under the causal
        // mask; cross-attention caches the encoder features after step 0
        // (flush on step 0 resets that cache for this segment).
        let ys = model
            .decoder
            .forward(&input, audio_features, step == 0)
            .map_err(|e| {
                fmt_stage_fail(
                    "transcribe.decode.forward",
                    e,
                    EngineError::TranscriptionFailed,
                )
            })?;
        let seq_len = ys.dim(1).map_err(|e| {
            fmt_stage_fail("transcribe.decode.dim", e, EngineError::TranscriptionFailed)
        })?;
        // Logits for the last position only.
        let last = ys
            .narrow(1, seq_len - 1, 1)
            .and_then(|h| model.decoder.final_linear(&h))
            .and_then(|l| l.i(0)?.i(0))
            .map_err(|e| {
                fmt_stage_fail(
                    "transcribe.decode.logits",
                    e,
                    EngineError::TranscriptionFailed,
                )
            })?;
        let mut biased = last.add(bias).map_err(|e| {
            fmt_stage_fail(
                "transcribe.decode.bias",
                e,
                EngineError::TranscriptionFailed,
            )
        })?;
        // begin-suppress: forbid an immediate <|endoftext|> so a leading silence
        // does not yield an empty segment.
        if step == 0 {
            biased = suppress_one(&biased, tokens.eot, config.vocab_size, device)?;
        }
        let next = biased
            .argmax(D::Minus1)
            .and_then(|t| t.to_scalar::<u32>())
            .map_err(|e| {
                fmt_stage_fail(
                    "transcribe.decode.argmax",
                    e,
                    EngineError::TranscriptionFailed,
                )
            })?;
        if next == tokens.eot {
            break;
        }
        seq.push(next);
    }
    Ok(seq[prompt_len..].to_vec())
}

/// Add `NEG_INFINITY` at a single token index (begin-suppress helper).
fn suppress_one(
    logits: &Tensor,
    token: u32,
    vocab: usize,
    device: &Device,
) -> Result<Tensor, EngineError> {
    let mut b = vec![0.0f32; vocab];
    if (token as usize) < vocab {
        b[token as usize] = f32::NEG_INFINITY;
    }
    let b = Tensor::from_vec(b, vocab, device).map_err(|e| {
        fmt_stage_fail(
            "transcribe.begin_suppress",
            e,
            EngineError::TranscriptionFailed,
        )
    })?;
    logits.add(&b).map_err(|e| {
        fmt_stage_fail(
            "transcribe.begin_suppress.add",
            e,
            EngineError::TranscriptionFailed,
        )
    })
}

/// Transcribe 16 kHz-mono PCM to text, emitting each 30 s segment's text through
/// `on_segment` as it completes (streaming, SYNC-V5) and returning the full
/// transcript. `on_segment` returning [`ControlFlow::Break`] stops early (the UI
/// "Stop" / vault-lock cancel seam) and returns what was decoded so far.
///
/// The PCM is zero-padded up to a whole number of 30 s windows (standard Whisper
/// preprocessing — the model is trained on 30 s inputs) and each window is
/// decoded independently. Language is detected once, on the first window, and
/// reused (a single note is one language) — never translated (SYNC-V3).
#[allow(clippy::too_many_arguments)]
pub fn transcribe_pcm(
    model: &mut Whisper,
    tokenizer: &Tokenizer,
    tokens: &WhisperTokens,
    config: &Config,
    mel_filters: &[f32],
    device: &Device,
    pcm: &[f32],
    on_segment: &mut dyn FnMut(&str) -> ControlFlow<()>,
) -> Result<String, EngineError> {
    if pcm.is_empty() {
        return Ok(String::new());
    }
    let bias = suppress_bias(config, tokens, device)?;

    // Pad to a whole number of 30 s windows so every decode sees a full window.
    let n_windows = pcm.len().div_ceil(N_SAMPLES).max(1);
    let mut padded = pcm.to_vec();
    padded.resize(n_windows * N_SAMPLES, 0.0);

    let mel_flat = whisper::audio::pcm_to_mel(config, &padded, mel_filters);
    let n_mels = config.num_mel_bins;
    let total_frames = mel_flat.len() / n_mels;
    let mel = Tensor::from_vec(mel_flat, (1, n_mels, total_frames), device)
        .map_err(|e| fmt_stage_fail("transcribe.mel", e, EngineError::TranscriptionFailed))?;

    let mut language_token: Option<u32> = None;
    let mut transcript = String::new();

    for w in 0..n_windows {
        let seek = w * N_FRAMES;
        // `pcm_to_mel` pads with an extra window's worth of frames, so the first
        // `n_windows * N_FRAMES` frames always exist.
        let mel_segment = mel.narrow(2, seek, N_FRAMES).map_err(|e| {
            fmt_stage_fail("transcribe.segment", e, EngineError::TranscriptionFailed)
        })?;
        model.reset_kv_cache();
        let audio_features = model.encoder.forward(&mel_segment, true).map_err(|e| {
            fmt_stage_fail("transcribe.encode", e, EngineError::TranscriptionFailed)
        })?;

        // Detect language once (multilingual only), reuse for later windows.
        if w == 0 && tokens.is_multilingual() {
            language_token = Some(detect_language(model, tokens, &audio_features, device)?);
        }

        // Prompt: sot [lang] transcribe no_timestamps — never translate (SYNC-V3).
        let mut prompt = vec![tokens.sot];
        if let Some(lang) = language_token {
            prompt.push(lang);
        }
        if let Some(tr) = tokens.transcribe {
            prompt.push(tr);
        }
        if let Some(nt) = tokens.no_timestamps {
            prompt.push(nt);
        }

        let ids = decode_segment(
            model,
            tokens,
            &bias,
            config,
            &audio_features,
            &prompt,
            device,
        )?;
        let text = tokenizer.decode(&ids, true).map_err(|e| {
            fmt_stage_fail("transcribe.detokenize", e, EngineError::TranscriptionFailed)
        })?;
        if !text.is_empty() {
            transcript.push_str(&text);
            if on_segment(&text).is_break() {
                return Ok(transcript);
            }
        }
    }

    Ok(transcript)
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn mel_filters_have_the_candle_expected_shape() {
        // candle indexes `filters[mel * (1 + N_FFT/2) + bin]`, so the flat length
        // must be n_mels * 201 for both the 80-bin (base) and 128-bin (large-v3)
        // model families.
        assert_eq!(mel_filters(80).len(), 80 * 201);
        assert_eq!(mel_filters(128).len(), 128 * 201);
    }

    #[test]
    fn mel_filters_are_nonnegative_and_nonzero() {
        // A slaney mel filterbank is all-nonnegative with real energy in it (each
        // triangle has positive area). A silently-empty matrix would zero the mel
        // spectrogram and transcribe nothing.
        let f = mel_filters(80);
        assert!(f.iter().all(|&w| w >= 0.0 && w.is_finite()));
        let total: f64 = f.iter().map(|&w| w as f64).sum();
        assert!(total > 0.0, "filterbank must carry energy, got sum {total}");
    }

    #[test]
    fn mel_scale_round_trips() {
        // hz → mel → hz is the identity (within f64 tolerance) across the linear
        // and logarithmic regions of the slaney scale.
        for &hz in &[0.0, 100.0, 999.0, 1000.0, 1500.0, 4000.0, 8000.0] {
            let back = mel_to_hz(hz_to_mel(hz));
            assert!(
                (back - hz).abs() < 1e-6,
                "round-trip failed at {hz}: got {back}"
            );
        }
    }

    #[test]
    fn mel_scale_is_continuous_at_the_1khz_knee() {
        // The linear/log break is at 1 kHz; a discontinuity there would warp the
        // whole filterbank. Approaching from both sides must agree.
        let below = hz_to_mel(1000.0 - 1e-3);
        let at = hz_to_mel(1000.0);
        assert!((at - below).abs() < 1e-3);
        assert!((at - 15.0).abs() < 1e-9, "the knee sits at mel 15.0");
    }
}

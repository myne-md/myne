//! On-device Whisper decode loop (voice-to-text, MYND-550; asr-engine task 3).
//!
//! The pure-compute + decode half of [`super::engine_candle`]'s `transcribe`:
//! the log-mel front end, language detection, and the greedy token-decode loop
//! over 30-second windows — all against candle-transformers 0.8.4's in-tree
//! `whisper` module (a **quantized GGUF** model + siblings `tokenizer.json` /
//! `config.json`, side-loaded like the generation model, SYNC-1/2).
//!
//! **Mel filterbank is computed, not shipped.** candle's `pcm_to_mel` needs a
//! caller-supplied mel-filter matrix; rather than commit an opaque
//! `melfilters.bytes` blob (dependency-policy provenance headache, and one blob
//! per `num_mel_bins`), [`mel_filters`] reproduces `librosa.filters.mel(sr=16000,
//! n_fft=400, n_mels, htk=False, norm="slaney")` deterministically in f64 → f32.
//! That matches OpenAI Whisper's own preprocessing (the blob the candle example
//! loads is generated by the identical librosa call) and works for any
//! `num_mel_bins` (80 for base/small, 128 for large-v3) with no data file.
//!
//! **Never translates (SYNC-V3).** The decode prompt is seeded with the detected
//! language token + `<|transcribe|>` — never `<|translate|>` — so speech is
//! transcribed in its own language, never silently rendered into English.
//!
//! Secret-handling (`src-tauri/AGENTS.md`): the PCM samples are decrypted audio
//! (AS1-class) and the produced transcript is note-class plaintext — **neither is
//! ever logged**; only the bounded [`EngineError`] kind escapes.

// Under the E2E `local-inference-stub` variant the production Candle path is
// compiled out (the setup uses `StubEngine`), so these items are unused there —
// silence dead_code for THAT build only, exactly like `engine_candle`.
#![cfg_attr(feature = "local-inference-stub", allow(dead_code))]


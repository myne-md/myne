// iOS WKWebView chrome tweaks that CANNOT be expressed from web code.
//
// The soft keyboard's "form assistant" bar — the ‹ › ⌄ Done strip WKWebView
// draws directly above the keyboard for any focused text field — is a NATIVE
// `inputAccessoryView` vended by the private `WKContentView` class. No CSS, JS,
// viewport trick, or `visualViewport` handling can remove it; it is drawn by
// UIKit, outside the web content. Native editors (Obsidian, Notion) suppress it
// exactly the way we do here: override `-[WKContentView inputAccessoryView]` to
// return `nil`.
//
// Why here (Rust) and not in `gen/apple/`: the iOS Xcode project is generated by
// `tauri ios init` and is NOT committed, so a Swift/ObjC edit there is wiped on
// the next regeneration. This runs from the Tauri `.setup()` hook in committed
// Rust, so it survives. It uses `objc2`, already compiled into the build via
// `wry` — referencing it adds a dependency EDGE but no new code to audit.

use objc2::ffi::{class_addMethod, class_getInstanceMethod, method_setImplementation};
use objc2::runtime::{AnyClass, AnyObject, Imp, Sel};
use objc2::sel;

/// Replacement implementation for `-inputAccessoryView`: return `nil` (no bar).
/// Signature matches `- (UIView *)inputAccessoryView` — `(self, _cmd) -> id`.
unsafe extern "C-unwind" fn no_input_accessory(_this: *mut AnyObject, _cmd: Sel) -> *mut AnyObject {
    core::ptr::null_mut()
}

/// Suppress the WKWebView keyboard form-assistant bar for the whole process.
/// Class-level swizzle, so it applies to every current and future web view.
/// Idempotent and safe to call once at startup; a no-op off WebKit runtimes.
pub fn suppress_keyboard_accessory_bar() {
    // WKContentView is the private UIView that actually vends the accessory bar.
    let Some(cls) = AnyClass::get(c"WKContentView") else {
        return; // WebKit not loaded / class absent — nothing to override.
    };
    let sel = sel!(inputAccessoryView);

    // The runtime IMP type is a bare `extern "C-unwind" fn()`; transmute our
    // typed function pointer to it (same ABI, different arity in the type).
    let imp: Imp = unsafe {
        core::mem::transmute::<
            unsafe extern "C-unwind" fn(*mut AnyObject, Sel) -> *mut AnyObject,
            Imp,
        >(no_input_accessory)
    };

    let cls_ptr: *const AnyClass = cls;
    // Type encoding for `id (id self, SEL _cmd)`.
    let types = c"@@:";

    unsafe {
        // WKContentView implements `inputAccessoryView` itself, so `addMethod`
        // reports it already exists (returns false) and we overwrite in place —
        // scoped to WKContentView, never the inherited UIResponder default.
        if !class_addMethod(cls_ptr.cast_mut(), sel, imp, types.as_ptr()).as_bool() {
            let method = class_getInstanceMethod(cls_ptr, sel);
            if !method.is_null() {
                method_setImplementation(method, imp);
            }
        }
    }
}

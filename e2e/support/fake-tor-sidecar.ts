// Fake `myne-tor` sidecar for the desktop E2E harness (MYND-650 task 10).
//
// The Tor-routing toggle spawns a real Tor client. A scenario must never do
// that: real Tor needs the network CI does not have, bootstraps in five to
// thirty seconds when it works at all, and would make "connecting" and
// "unavailable" depend on the state of the volunteer relay network. So the
// harness supplies its own sidecar — a **fake SOCKS5 proxy** that speaks
// exactly the two things the host reads from the real one:
//
//   * a listener on the `-p` port answering the SOCKS5 method negotiation the
//     supervisor's liveness probe sends (`supervisor.rs::socks5_greeting_ok`);
//   * arti's `"Sufficiently bootstrapped"` INFO line on stderr, which is the
//     only readiness signal this build of arti exposes
//     (`arti_cli.rs::is_bootstrap_line`).
//
// Nothing in production changes. The supervisor, the phase machine, the routing
// gate, the IPC and the UI are all the shipped ones; the only substitution is
// the Tor client at the end of the pipe, which is what the scenario is
// deliberately NOT testing (real-Tor traversal is a manual procedure — task 12).
//
// ## Why the process is driven by a file
//
// The fake reads a **control file** and reacts to it, rather than following a
// timer. `connecting → active → dead` then happens exactly when the scenario
// says, with no sleep to tune and no race to lose on a loaded runner. The file
// lives beside the generated `arti.toml`, i.e. under the session's own
// `XDG_DATA_HOME` — per-run isolated like every other fixture surface, and
// reachable by the fake because the host hands it that path in `-c`.
//
// ## Why it is installed beside the binary
//
// `tor_sidecar::supervisor::sidecar_path` resolves `myne-tor` next to the
// running executable, which is where Tauri stages an `externalBin`. That
// directory is the build output, shared by every scenario — so
// `installFakeTorSidecar` moves any real sidecar aside and its returned
// uninstall puts it back. Call it in a `try`/`finally` around `scenario(...)`.

import {
  chmodSync,
  existsSync,
  mkdirSync,
  readdirSync,
  readFileSync,
  realpathSync,
  renameSync,
  rmSync,
  writeFileSync,
} from "node:fs";
import { dirname, join } from "node:path";
import { defaultAppPath } from "./session";

/** Where the fake parks a real staged sidecar for the duration of a scenario. */
const PARKED_SUFFIX = ".e2e-parked";

/** The control words the fake understands (see `fakeSidecarSource`). */
type ControlWord = "bootstrap" | "die";

function fakeSidecarSource(): string {
  // The shebang names the interpreter running the suite rather than
  // `/usr/bin/env node`, so the fake cannot pick up a different Node from the
  // app's inherited PATH (the supervisor spawns it, not a shell).
  return `#!${process.execPath}
// GENERATED by e2e/support/fake-tor-sidecar.ts — not a source file.
"use strict";
const net = require("node:net");
const fs = require("node:fs");
const path = require("node:path");

// **The very first thing it does, before the argv assert can exit.** Without
// this, "no bind report" has two answers that need opposite fixes: the fake is
// not the process the host spawned at all, or it IS and it exited before
// listening. The -c argument is the only place the per-run directory is known,
// so the marker goes next to it, and it is best-effort.
const argv = process.argv.slice(2);
try {
  const ci = argv.indexOf("-c");
  if (ci >= 0 && ci + 1 < argv.length) {
    require("node:fs").writeFileSync(
      require("node:path").join(require("node:path").dirname(argv[ci + 1]), "e2e-started"),
      argv.join(" "),
    );
  }
} catch {}
function flag(name) {
  const i = argv.indexOf(name);
  return i >= 0 && i + 1 < argv.length ? argv[i + 1] : null;
}
const port = Number(flag("-p"));
const configFile = flag("-c");
// Assert the invocation rather than tolerate it: if the host's argv ever
// changes shape, this fixture should fail loudly instead of quietly never
// listening (which would look like a Tor bootstrap that simply never finished).
if (!argv.includes("proxy") || !Number.isInteger(port) || port <= 0 || !configFile) {
  console.error("fake myne-tor: unexpected argv: " + argv.join(" "));
  process.exit(2);
}

const control = path.join(path.dirname(configFile), "e2e-control");
const bindReport = path.join(path.dirname(configFile), "e2e-bind");

const server = net.createServer((socket) => {
  socket.on("error", () => {});
  let buf = Buffer.alloc(0);
  let negotiated = false;
  socket.on("data", (chunk) => {
    if (!negotiated) {
      buf = Buffer.concat([buf, chunk]);
      // VER=5, NMETHODS, methods… — reply NO-AUTH, exactly what the host's
      // liveness probe expects and nothing more.
      if (buf.length >= 2 && buf[0] === 0x05 && buf.length >= 2 + buf[1]) {
        negotiated = true;
        socket.write(Buffer.from([0x05, 0x00]));
      }
      return;
    }
    // Past the greeting this can only be a CONNECT. This proxy reaches no
    // network at all, so it answers honestly — 0x04 "host unreachable" — rather
    // than pretending to hold a circuit it does not have.
    socket.write(Buffer.from([0x05, 0x04, 0x00, 0x01, 0, 0, 0, 0, 0, 0]));
    socket.end();
  });
});

// **Whether the bind SUCCEEDED, written where the scenario can read it.**
// Until this existed the only report was stderr, which goes to the supervisor's
// pipe and nowhere a scenario can reach — so a fake that failed to bind was
// indistinguishable from one that bootstrapped late. That matters because the
// host picks the port by binding :0, reading the number and DROPPING the
// listener before handing it over, so the child races anything else on the box
// for it. The scenario reaching \`connecting\` proves only that the process was
// spawned: the phase is set right after spawn, before any stderr is read.
server.on("error", (e) => {
  try { fs.writeFileSync(bindReport, "failed " + e.message); } catch {}
  console.error("fake myne-tor: listen failed: " + e.message);
  process.exit(1);
});

server.listen(port, "127.0.0.1", () => {
  try { fs.writeFileSync(bindReport, "listening " + port); } catch {}
  // Deliberately NOT the readiness marker: the supervisor must stay in
  // \`Starting\` until the scenario writes "bootstrap". Mirrors arti's own
  // startup chatter, which is_bootstrap_line() drops.
  console.error("INFO fake-arti: Starting fake Arti on 127.0.0.1:" + port);
  poll();
});

let bootstrapped = false;
function poll() {
  let want = "";
  try {
    want = fs.readFileSync(control, "utf8").trim();
  } catch {
    want = "";
  }
  if (want === "die") {
    // Exit without a stop request: EOF on stderr is how the supervisor learns
    // the client is gone, and an exit it did not ask for is a failure.
    process.exit(1);
  }
  if (want === "bootstrap" && !bootstrapped) {
    bootstrapped = true;
    // The shape arti 2.5.0 emits, tracing prefix included — the same line
    // \`arti_cli\`'s own unit test pins.
    console.error(
      "2026-07-31T00:00:00Z  INFO arti::subcommands::proxy: Sufficiently bootstrapped; proxy now functional.",
    );
  }
  setTimeout(poll, 100);
}
`;
}

/**
 * Put the fake sidecar where the app will look for one, parking any real
 * `myne-tor` staged there. Returns the uninstall — call it in a `finally`, so a
 * failing scenario cannot leave the build output holding a fixture.
 */
export function installedFakePath(): string {
  return join(dirname(realpathSync(defaultAppPath())), "myne-tor");
}

/**
 * Whether the file the app will spawn is THIS fixture rather than a real sidecar.
 *
 * The fake writes a start marker before anything in it can fail, and a run
 * measured that marker absent while the host had clearly spawned something (the
 * phase reached `connecting` and the tor directory held the generated config).
 * The only way both are true is that the process spawned was not the fake, so
 * the install needs an assertion rather than an assumption: the fixture is a
 * Node script and begins with a shebang, a real `myne-tor` is an ELF.
 */
export function fakeIsInstalled(): boolean {
  try {
    return readFileSync(installedFakePath(), "utf8").startsWith("#!");
  } catch {
    return false;
  }
}

export function installFakeTorSidecar(): () => void {
  // `realpathSync` because the app resolves its own location with
  // `std::env::current_exe()`, which follows symlinks. A `MYNE_E2E_APP` pointing
  // at a link into some other target dir would otherwise put the fake in a
  // directory the app never looks in — and the symptom would be a Tor client
  // that simply never starts, not a missing file.
  const exeDir = dirname(realpathSync(defaultAppPath()));
  const target = join(exeDir, "myne-tor");
  const parked = target + PARKED_SUFFIX;
  // **Park the REAL one, never a fixture, and restore whatever is parked.**
  //
  // The original pair asked `existsSync(target)` and treated any answer as "a
  // real sidecar is here". A run killed before its `finally` leaves the fixture
  // in place AND the real one parked, and the next install then renamed the
  // FIXTURE over the parked real binary, destroying it. Its uninstall restored
  // that fixture as though it were the sidecar, and one round later the file was
  // gone from the build output entirely — measured, on this machine: `myne-tor`
  // absent and a 19.7 MB ELF sitting at `myne-tor.e2e-parked`.
  //
  // Two changes make it idempotent. Parking is keyed on the file being a real
  // binary rather than merely present, so a leftover fixture is overwritten
  // instead of promoted. Restoring is keyed on a parked file EXISTING rather
  // than on what this call happened to observe, so a crashed predecessor's
  // parked binary is put back by whoever runs next.
  const leftoverFixture = existsSync(target) && !fakeIsInstalled();
  if (leftoverFixture) renameSync(target, parked);
  writeFileSync(target, fakeSidecarSource());
  chmodSync(target, 0o755);
  return () => {
    rmSync(target, { force: true });
    if (existsSync(parked)) renameSync(parked, target);
  };
}

/**
 * The scenario's half of the control file: the two things it can tell a
 * running fake to do.
 *
 * `appDataDir` is the session's own (`AppSession.appDataDir`), so two
 * concurrently-sharded runs never see each other's control file.
 */
export function torSidecarControl(appDataDir: string): {
  bootstrap(): void;
  die(): void;
  bindOutcome(): string;
} {
  const torDir = join(appDataDir, "tor");
  const write = (word: ControlWord) => {
    // The host creates `tor/` when it starts the sidecar; create it anyway so a
    // control write is never a race against that.
    mkdirSync(torDir, { recursive: true });
    writeFileSync(join(torDir, "e2e-control"), word);
  };
  return {
    /** Complete the fake's bootstrap: the readiness line, then the probe. */
    bootstrap: () => write("bootstrap"),
    /** Kill the fake from the inside — an exit the host did not ask for. */
    die: () => write("die"),
    /**
     * What the fake's own `listen` reported: `listening <port>`, `failed <why>`,
     * or `not written` when it never got that far.
     *
     * The scenario cannot otherwise tell a fake that bound its port from one
     * that lost the race for it, because the phase reaches `connecting` right
     * after the spawn and before any stderr is read. A lost race then presents
     * as `unavailable` a moment later, which reads like a bootstrap that failed
     * rather than a process that was never listening.
     */
    bindOutcome: () => {
      try {
        return readFileSync(join(torDir, "e2e-bind"), "utf8").trim();
      } catch {
        // **What IS in the directory, when the report is not.** The fake writes
        // its outcome beside the `arti.toml` the host generated, so the presence
        // of that config proves the host prepared the directory and got as far
        // as spawning something; the absence of the report then says the thing
        // it spawned was not this fake. Without this the failure is
        // indistinguishable from the host never having started a sidecar at all.
        let listing: string;
        try {
          listing = readdirSync(torDir).sort().join(" ") || "empty";
        } catch {
          listing = "no tor/ directory";
        }
        // `e2e-started` is written by the fake before its argv assert can exit,
        // so its presence separates "the fake ran and died" from "the fake is
        // not what the host spawned" — two answers needing opposite fixes.
        const started = existsSync(join(torDir, "e2e-started"))
          ? "the fake DID start"
          : "the fake never started";
        return `not written (${started}; tor dir holds: ${listing})`;
      }
    },
  };
}
